class ElectraForMultiTaskClassification(nn.Module):
    def __init__(self, model_name, num_fallacy_labels, num_hate_labels, task_weights=None, dropout_rate=0.1):
        super().__init__()
        self.electra = ElectraModel.from_pretrained(model_name)
        hidden_size = self.electra.config.hidden_size

        # Use task-specific heads instead of simple layer norm + linear layers
        self.fallacy_head = TaskSpecificHead(hidden_size, num_fallacy_labels, dropout_rate)
        self.hate_head = TaskSpecificHead(hidden_size, num_hate_labels, dropout_rate)
        self.rationale_head = TaskSpecificHead(hidden_size, 2, dropout_rate)

        # Shared dropout for initial representation
        self.dropout = nn.Dropout(dropout_rate)

        # Default weights if not provided
        self.task_weights = task_weights or {
            'fallacy': 1.0,
            'hate': 1.0,
            'rationale': 0.5
        }

        self.loss_fct = nn.CrossEntropyLoss()

    # Add these methods for gradient checkpointing
    def gradient_checkpointing_enable(self, gradient_checkpointing_kwargs=None):
        """Enable gradient checkpointing for the model."""
        self.electra.gradient_checkpointing_enable(gradient_checkpointing_kwargs=gradient_checkpointing_kwargs)

    def gradient_checkpointing_disable(self):
        """Disable gradient checkpointing for the model."""
        self.electra.gradient_checkpointing_disable()

    def forward(self, input_ids=None, attention_mask=None, token_type_ids=None,
                fallacy_labels=None, hate_labels=None, rationale_labels=None,
                return_dict=True, **kwargs):
        # Get the hidden states from the electra encoder
        outputs = self.electra(
            input_ids,
            attention_mask=attention_mask,
            token_type_ids=token_type_ids
        )

        # ELECTRA doesn't have a pooler, so we use the [CLS] token representation
        sequence_output = outputs.last_hidden_state
        cls_output = sequence_output[:, 0, :]  # Get [CLS] token representation

        # Apply shared dropout first
        cls_output = self.dropout(cls_output)

        # Use task-specific heads for each task
        fallacy_logits = self.fallacy_head(cls_output)
        hate_logits = self.hate_head(cls_output)

        # For token classification (rationales), we need to apply the head to each token
        # Apply the dropout to the sequence first
        sequence_output = self.dropout(sequence_output)

        # Process sequence for rationale detection (token classification)
        batch_size, seq_length, hidden_size = sequence_output.shape

        # There are two ways to handle this:
        # Option 1: Process each token position separately (more accurate but slower)
        rationale_logits = torch.zeros(batch_size, seq_length, 2, device=sequence_output.device)
        for i in range(seq_length):
            rationale_logits[:, i, :] = self.rationale_head(sequence_output[:, i, :])

        # Option 2: Reshape and process all tokens at once (faster but uses more memory)
        # flat_sequence = sequence_output.view(-1, hidden_size)
        # flat_rationale_logits = self.rationale_head(flat_sequence)
        # rationale_logits = flat_rationale_logits.view(batch_size, seq_length, 2)

        loss = None
        if fallacy_labels is not None and hate_labels is not None and rationale_labels is not None:
            # Create masks for valid labels (ignore -100)
            fallacy_mask = fallacy_labels != -100
            hate_mask = hate_labels != -100
            rationale_mask = rationale_labels.view(-1) != -100

            # Calculate losses only for valid labels
            fallacy_loss = (self.loss_fct(fallacy_logits[fallacy_mask], fallacy_labels[fallacy_mask])
                            if fallacy_mask.any() else torch.tensor(0.0).to(fallacy_logits.device))

            hate_loss = (self.loss_fct(hate_logits[hate_mask], hate_labels[hate_mask])
                         if hate_mask.any() else torch.tensor(0.0).to(hate_logits.device))

            # Flatten and reshape for token classification
            rationale_loss = (self.loss_fct(
                rationale_logits.view(-1, 2)[rationale_mask],
                rationale_labels.view(-1)[rationale_mask]
            ) if rationale_mask.any() else torch.tensor(0.0).to(rationale_logits.device))

            # Weighted sum of losses
            loss = (
                    self.task_weights['fallacy'] * fallacy_loss +
                    self.task_weights['hate'] * hate_loss +
                    self.task_weights['rationale'] * rationale_loss
            )

        if not return_dict:
            return (loss, fallacy_logits, hate_logits, rationale_logits)

        return {
            'loss': loss,
            'fallacy_logits': fallacy_logits,
            'hate_logits': hate_logits,
            'rationale_logits': rationale_logits
        }

    def state_dict(self, *args, **kwargs):
        sd = super().state_dict(*args, **kwargs)
        return {k: v.contiguous() for k, v in sd.items()}

    def save_pretrained(self, save_directory):
        """Save model weights and configuration"""
        os.makedirs(save_directory, exist_ok=True)
        torch.save(self.state_dict(), os.path.join(save_directory, "pytorch_model.bin"))
        # Save configuration
        config = {
            "model_name": self.electra.config._name_or_path,
            "num_fallacy_labels": self.fallacy_head.classifier.out_features,
            "num_hate_labels": self.hate_head.classifier.out_features,
            "task_weights": self.task_weights
        }
        with open(os.path.join(save_directory, "config.json"), "w", encoding="utf-8") as f:
            json.dump(config, f, indent=2)

    @classmethod
    def from_pretrained(cls, load_directory):
        """Load model from saved weights and configuration"""
        try:
            with open(os.path.join(load_directory, "config.json"), "r", encoding="utf-8") as f:
                config = json.load(f)

            # Create model with saved configuration
            task_weights = config.get("task_weights", None)
            model = cls(
                config["model_name"],
                config["num_fallacy_labels"],
                config["num_hate_labels"],
                task_weights
            )

            # Load weights
            state_dict = torch.load(
                os.path.join(load_directory, "pytorch_model.bin"),
                map_location="cpu"
            )
            model.load_state_dict(state_dict)
            return model
        except Exception as e:
            print(f"Error loading model: {e}")
            raise


class TaskSpecificHead(nn.Module):
    def __init__(self, hidden_size, num_labels, dropout_rate=0.1):
        super().__init__()
        self.layernorm = nn.LayerNorm(hidden_size)
        self.dropout = nn.Dropout(dropout_rate)
        self.classifier = nn.Linear(hidden_size, num_labels)

    def forward(self, hidden_states):
        # Apply layer normalization first
        normalized = self.layernorm(hidden_states)
        # Apply dropout
        dropped = self.dropout(normalized)
        # Apply classification layer
        logits = self.classifier(dropped)
        return logits

def compute_metrics(eval_pred):
    """Compute metrics for model evaluation with per-class breakdown"""
    logits, labels = eval_pred

    # Check the structure of labels
    if isinstance(labels, tuple):
        # If labels is a tuple, unpack it
        f_labels, h_labels, r_labels = labels
    else:
        # If labels is a dict, extract from it
        f_labels = labels.get('fallacy_labels')
        h_labels = labels.get('hate_labels')
        r_labels = labels.get('rationale_labels')

    # Handle different output formats for predictions
    if isinstance(logits, tuple):
        f_logits, h_logits, r_logits = logits
    else:
        f_logits = logits.get('fallacy_logits')
        h_logits = logits.get('hate_logits')
        r_logits = logits.get('rationale_logits')

    # Get predictions by taking argmax
    f_preds = np.argmax(f_logits, axis=-1)
    h_preds = np.argmax(h_logits, axis=-1)
    r_preds = np.argmax(r_logits.reshape(-1, 2), axis=-1).reshape(r_logits.shape[0], -1)

    # Create masks for valid labels
    valid_f = f_labels != -100
    valid_h = h_labels != -100
    valid_r = r_labels.reshape(-1) != -100

    # Calculate metrics (ignore -100)
    metrics = {}

    # Fallacy metrics - with per-class breakdown
    if valid_f.any():
        # Macro-averaged metrics
        p_f, r_f, f1_f, _ = precision_recall_fscore_support(
            f_labels[valid_f], f_preds[valid_f], average="macro"
        )
        metrics.update({
            "f1_fallacy": f1_f,
            "precision_fallacy": p_f,
            "recall_fallacy": r_f
        })

        # Per-class metrics
        _, _, f1_per_class, support_per_class = precision_recall_fscore_support(
            f_labels[valid_f], f_preds[valid_f], average=None
        )

        # Get unique class labels
        unique_classes = np.unique(f_labels[valid_f])

        # Add per-class metrics
        for cls in unique_classes:
            idx = np.where(unique_classes == cls)[0][0]
            metrics[f"f1_fallacy_class_{cls}"] = f1_per_class[idx]
            metrics[f"support_fallacy_class_{cls}"] = int(support_per_class[idx])
    else:
        metrics["f1_fallacy"] = 0.0

    # Hate speech metrics - with per-class breakdown
    if valid_h.any():
        # Macro-averaged metrics
        p_h, r_h, f1_h, _ = precision_recall_fscore_support(
            h_labels[valid_h], h_preds[valid_h], average="macro"
        )
        metrics.update({
            "f1_hate": f1_h,
            "precision_hate": p_h,
            "recall_hate": r_h
        })

        # Per-class metrics
        _, _, f1_per_class, support_per_class = precision_recall_fscore_support(
            h_labels[valid_h], h_preds[valid_h], average=None
        )

        # Get unique class labels
        unique_classes = np.unique(h_labels[valid_h])

        # Add per-class metrics
        for cls in unique_classes:
            idx = np.where(unique_classes == cls)[0][0]
            metrics[f"f1_hate_class_{cls}"] = f1_per_class[idx]
            metrics[f"support_hate_class_{cls}"] = int(support_per_class[idx])
    else:
        metrics["f1_hate"] = 0.0

    # Rationale metrics - with per-class breakdown
    if valid_r.any():
        flat_r_preds = r_preds.reshape(-1)[valid_r]
        flat_r_labels = r_labels.reshape(-1)[valid_r]

        # Macro-averaged metrics
        p_r, r_r, f1_r, _ = precision_recall_fscore_support(
            flat_r_labels, flat_r_preds, average="macro"
        )
        metrics.update({
            "f1_rationale": f1_r,
            "precision_rationale": p_r,
            "recall_rationale": r_r
        })

        # Per-class metrics
        _, _, f1_per_class, support_per_class = precision_recall_fscore_support(
            flat_r_labels, flat_r_preds, average=None
        )

        # Get unique class labels
        unique_classes = np.unique(flat_r_labels)

        # Add per-class metrics
        for cls in unique_classes:
            idx = np.where(unique_classes == cls)[0][0]
            metrics[f"f1_rationale_class_{cls}"] = f1_per_class[idx]
            metrics[f"support_rationale_class_{cls}"] = int(support_per_class[idx])
    else:
        metrics["f1_rationale"] = 0.0

    # Overall F1 (average of all tasks)
    metrics["f1"] = (metrics["f1_fallacy"] + metrics["f1_hate"] + metrics["f1_rationale"]) / 3

    return metrics
    pass

